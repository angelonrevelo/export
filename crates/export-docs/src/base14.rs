/// One built-in font: the descent, the default width, and the widths
/// keyed by glyph name.
pub(crate) struct Base14 {
    pub(crate) descent: f64,
    pub(crate) default_width: f64,
    pub(crate) widths: HashMap<String, f64>,
}

pub(crate) fn base14() -> &'static HashMap<String, Base14> {
    static MAP: OnceLock<HashMap<String, Base14>> = OnceLock::new();
    MAP.get_or_init(|| {
        let mut fonts: HashMap<String, Base14> = HashMap::new();
        let mut current: Option<String> = None;
        for line in BASE14.lines() {
            if let Some(rest) = line.strip_prefix("  ") {
                let Some(top) = current.as_ref().and_then(|name| fonts.get_mut(name)) else {
                    continue;
                };
                let (key, width) = rest.split_once(' ').unwrap_or((rest, "0"));
                let width: f64 = width.parse().unwrap_or(0.0);
                // Single characters were written as u0041; decode them back
                // so lookups by the character's unicode hit them.
                let key = if let Some(hex) = key.strip_prefix('u') {
                    match u32::from_str_radix(hex, 16).ok().and_then(char::from_u32) {
                        Some(ch) => ch.to_string(),
                        None => key.to_string(),
                    }
                } else {
                    key.to_string()
                };
                top.widths.insert(key, width);
            } else if let Some((name, rest)) = line.split_once(' ') {
                let mut parts = rest.split(' ');
                let descent: f64 = parts
                    .next()
                    .and_then(|v| v.parse().ok())
                    .unwrap_or(0.0);
                let missing: f64 = parts
                    .next()
                    .and_then(|v| v.parse().ok())
                    .unwrap_or(0.0);
                current = Some(name.to_string());
                fonts.insert(
                    name.to_string(),
                    Base14 {
                        descent,
                        default_width: missing,
                        widths: HashMap::new(),
                    },
                );
            }
        }
        fonts
    })
}
