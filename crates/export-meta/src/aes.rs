const RCON: [u8; 10] = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36];

/// Expanded AES-128 key. Built once per password check, then reused for every block.
#[derive(Clone)]
pub struct Aes128 {
    round: [[u8; 16]; 11],
}

impl Aes128 {
    pub fn new(key: &[u8; 16]) -> Self {
        let mut w = [0u8; 176];
        w[..16].copy_from_slice(key);
        let mut i = 16;
        let mut rcon_i = 0;
        while i < 176 {
            let mut t = [w[i - 4], w[i - 3], w[i - 2], w[i - 1]];
            if i % 16 == 0 {
                let x = t[0];
                t[0] = t[1];
                t[1] = t[2];
                t[2] = t[3];
                t[3] = x;
                for b in &mut t {
                    *b = SBOX[*b as usize];
                }
                t[0] ^= RCON[rcon_i];
                rcon_i += 1;
            }
            for byte in t {
                w[i] = w[i - 16] ^ byte;
                i += 1;
            }
        }
        let mut round = [[0u8; 16]; 11];
        for r in 0..11 {
            round[r].copy_from_slice(&w[r * 16..r * 16 + 16]);
        }
        Self { round }
    }

    pub fn encrypt_block(&self, block: &[u8; 16]) -> [u8; 16] {
        let mut s = *block;
        add_round(&mut s, &self.round[0]);
        for r in 1..10 {
            sub(&mut s, &SBOX);
            shift_rows(&mut s);
            mix(&mut s);
            add_round(&mut s, &self.round[r]);
        }
        sub(&mut s, &SBOX);
        shift_rows(&mut s);
        add_round(&mut s, &self.round[10]);
        s
    }

    pub fn decrypt_block(&self, block: &[u8; 16]) -> [u8; 16] {
        let mut s = *block;
        add_round(&mut s, &self.round[10]);
        for r in (1..10).rev() {
            inv_shift_rows(&mut s);
            sub(&mut s, &INV_SBOX);
            add_round(&mut s, &self.round[r]);
            inv_mix(&mut s);
        }
        inv_shift_rows(&mut s);
        sub(&mut s, &INV_SBOX);
        add_round(&mut s, &self.round[0]);
        s
    }
}

fn add_round(s: &mut [u8; 16], key: &[u8; 16]) {
    for i in 0..16 {
        s[i] ^= key[i];
    }
}

fn sub(s: &mut [u8; 16], box_: &[u8; 256]) {
    for b in s.iter_mut() {
        *b = box_[*b as usize];
    }
}

fn shift_rows(s: &mut [u8; 16]) {
    let t = s[1];
    s[1] = s[5];
    s[5] = s[9];
    s[9] = s[13];
    s[13] = t;
    let a = s[2];
    let b = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = a;
    s[14] = b;
    let t = s[15];
    s[15] = s[11];
    s[11] = s[7];
    s[7] = s[3];
    s[3] = t;
}

fn inv_shift_rows(s: &mut [u8; 16]) {
    let t = s[13];
    s[13] = s[9];
    s[9] = s[5];
    s[5] = s[1];
    s[1] = t;
    let a = s[2];
    let b = s[6];
    s[2] = s[10];
    s[6] = s[14];
    s[10] = a;
    s[14] = b;
    let t = s[3];
    s[3] = s[7];
    s[7] = s[11];
    s[11] = s[15];
    s[15] = t;
}

fn mix(s: &mut [u8; 16]) {
    for c in 0..4 {
        let i = c * 4;
        let a0 = s[i];
        let a1 = s[i + 1];
        let a2 = s[i + 2];
        let a3 = s[i + 3];
        s[i] = mul(a0, 2) ^ mul(a1, 3) ^ a2 ^ a3;
        s[i + 1] = a0 ^ mul(a1, 2) ^ mul(a2, 3) ^ a3;
        s[i + 2] = a0 ^ a1 ^ mul(a2, 2) ^ mul(a3, 3);
        s[i + 3] = mul(a0, 3) ^ a1 ^ a2 ^ mul(a3, 2);
    }
}

fn inv_mix(s: &mut [u8; 16]) {
    for c in 0..4 {
        let i = c * 4;
        let a0 = s[i];
        let a1 = s[i + 1];
        let a2 = s[i + 2];
        let a3 = s[i + 3];
        s[i] = mul(a0, 14) ^ mul(a1, 11) ^ mul(a2, 13) ^ mul(a3, 9);
        s[i + 1] = mul(a0, 9) ^ mul(a1, 14) ^ mul(a2, 11) ^ mul(a3, 13);
        s[i + 2] = mul(a0, 13) ^ mul(a1, 9) ^ mul(a2, 14) ^ mul(a3, 11);
        s[i + 3] = mul(a0, 11) ^ mul(a1, 13) ^ mul(a2, 9) ^ mul(a3, 14);
    }
}

fn mul(mut a: u8, mut n: u8) -> u8 {
    let mut p = 0u8;
    for _ in 0..8 {
        if n & 1 != 0 {
            p ^= a;
        }
        let hi = a & 0x80;
        a <<= 1;
        if hi != 0 {
            a ^= 0x1b;
        }
        n >>= 1;
    }
    p
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fips_197_c1() {
        let key = hex16("000102030405060708090a0b0c0d0e0f");
        let plain = hex16("00112233445566778899aabbccddeeff");
        let cipher = hex16("69c4e0d86a7b0430d8cdb78070b4c55a");
        let aes = Aes128::new(&key);
        assert_eq!(aes.encrypt_block(&plain), cipher);
        assert_eq!(aes.decrypt_block(&cipher), plain);
    }

    fn hex16(s: &str) -> [u8; 16] {
        let mut out = [0u8; 16];
        for i in 0..16 {
            out[i] = u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).unwrap();
        }
        out
    }
}
